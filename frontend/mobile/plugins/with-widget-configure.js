// Opens MoFin when a home screen widget is added so the user picks what it shows (an account for
// summaries, goals for Goals), via a widget "configure" activity named in the widget's info XML.
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const ACTIVITY = 'WidgetConfigureActivity';

function activitySource(androidPackage, scheme) {
  return `package ${androidPackage}

import android.app.Activity
import android.appwidget.AppWidgetManager
import android.content.Intent
import android.net.Uri
import android.os.Bundle

// Generated by plugins/with-widget-configure.js. Do not edit: changes are lost on prebuild.
class ${ACTIVITY} : Activity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    val id = intent?.extras?.getInt(AppWidgetManager.EXTRA_APPWIDGET_ID, AppWidgetManager.INVALID_APPWIDGET_ID)
      ?: AppWidgetManager.INVALID_APPWIDGET_ID
    if (id == AppWidgetManager.INVALID_APPWIDGET_ID) {
      setResult(RESULT_CANCELED)
      finish()
      return
    }
    // Accept the widget straight away: the choices are made in the app.
    setResult(RESULT_OK, Intent().putExtra(AppWidgetManager.EXTRA_APPWIDGET_ID, id))

    // "<package>.WeeklySummaryProvider" -> "WeeklySummary", the widget's name in app.config.ts.
    val provider = AppWidgetManager.getInstance(this).getAppWidgetInfo(id)?.provider?.className.orEmpty()
    val widget = provider.substringAfterLast('.').removeSuffix("Provider")
    if (widget.isNotEmpty()) {
      startActivity(
        Intent(Intent.ACTION_VIEW, Uri.parse("${scheme}://widget-setup?widget=" + Uri.encode(widget)))
          .setPackage(packageName)
          .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
      )
    }
    finish()
  }
}
`;
}

function withWidgetConfigure(config) {
  const scheme = Array.isArray(config.scheme) ? config.scheme[0] : config.scheme;
  if (!scheme) throw new Error('with-widget-configure: app.config needs a `scheme` for the setup link.');

  config = withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.activity = (app.activity ?? []).filter((a) => a.$['android:name'] !== `.${ACTIVITY}`);
    app.activity.push({
      $: {
        'android:name': `.${ACTIVITY}`,
        'android:exported': 'true',
        'android:excludeFromRecents': 'true',
        'android:noHistory': 'true',
        'android:taskAffinity': '',
        'android:theme': '@android:style/Theme.Translucent.NoTitleBar',
      },
      'intent-filter': [{ action: [{ $: { 'android:name': 'android.appwidget.action.APPWIDGET_CONFIGURE' } }] }],
    });
    return cfg;
  });

  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const androidPackage = AndroidConfig.Package.getPackage(cfg);
      if (!androidPackage) throw new Error('with-widget-configure: android.package is required.');
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/java', ...androidPackage.split('.'));
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${ACTIVITY}.kt`), activitySource(androidPackage, scheme));
      return cfg;
    },
  ]);
}

module.exports = withWidgetConfigure;
