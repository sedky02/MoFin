#!/usr/bin/env node
// Keeps the app's lucide icons out of the package barrel. Metro doesn't tree-shake, so
// `import { Wallet } from 'lucide-react-native'` puts all ~1,600 icons in the bundle. This script:
//   1. collects every icon the app imports (from 'lucide-react-native' or '@/lib/icons'),
//   2. writes src/lib/icons.ts, which re-exports each one from its own file
//      ('lucide-react-native/icons/<file>'), so only those reach the bundle,
//   3. points value imports of 'lucide-react-native' at '@/lib/icons' (type imports stay).
// Usage: node scripts/sync-icons.mjs [--check]   (--check: exit 1 if anything would change)
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const src = join(root, 'src');
const out = join(src, 'lib', 'icons.ts');
const barrel = join(root, 'node_modules', 'lucide-react-native', 'dist', 'esm', 'lucide-react-native.mjs');
const check = process.argv.includes('--check');

// Icon name -> file, from the package's own barrel (aliases such as Home -> house included).
const fileOf = new Map();
for (const m of readFileSync(barrel, 'utf8').matchAll(/export \{([^}]*)\} from '\.\/icons\/([^']+)\.mjs';/g)) {
  for (const spec of m[1].split(',')) {
    const name = spec.trim().match(/as (\w+)$/)?.[1];
    if (name) fileOf.set(name, m[2]);
  }
}

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) return walk(p);
    return /\.(ts|tsx)$/.test(f) && p !== out ? [p] : [];
  });
}

const IMPORT = /import\s*\{([^}]*)\}\s*from\s*['"](lucide-react-native|@\/lib\/icons)['"];?/g;
// src/core is a copy of the web's code: read its icons, but leave its text to scripts/core-drift.mjs.
const core = join(src, 'core');
const used = new Set();
const changed = [];

for (const file of walk(src)) {
  const text = readFileSync(file, 'utf8');
  const readOnly = file.startsWith(core);
  let next = text.replace(IMPORT, (_all, specs, from) => {
    const parts = specs.split(',').map((s) => s.trim()).filter(Boolean);
    const types = parts.filter((s) => s.startsWith('type ')).map((s) => s.slice(5));
    const values = parts.filter((s) => !s.startsWith('type '));
    values.forEach((v) => used.add(v.split(/\s+as\s+/)[0]));
    if (readOnly || (from === '@/lib/icons' && types.length === 0)) return _all;
    const lines = [];
    if (types.length) lines.push(`import type { ${types.join(', ')} } from 'lucide-react-native';`);
    if (values.length) lines.push(`import { ${values.join(', ')} } from '@/lib/icons';`);
    return lines.join('\n');
  });
  if (next !== text) {
    changed.push(relative(root, file));
    if (!check) writeFileSync(file, next);
  }
}

const unknown = [...used].filter((n) => !fileOf.has(n));
if (unknown.length) {
  console.error(`Not lucide icons: ${unknown.join(', ')}`);
  process.exit(1);
}

const body = [...used]
  .sort()
  .map((n) => `export { default as ${n} } from 'lucide-react-native/icons/${fileOf.get(n)}';`)
  .join('\n');
const generated = `// GENERATED by scripts/sync-icons.mjs (npm run icons:sync). Do not edit by hand.
// Each icon comes from its own file so the bundle carries only these, not lucide's whole set.
export type { LucideIcon } from 'lucide-react-native';
${body}
`;
let current = '';
try {
  current = readFileSync(out, 'utf8');
} catch {}
if (current !== generated) {
  changed.push(relative(root, out));
  if (!check) writeFileSync(out, generated);
}

if (check && changed.length) {
  console.error(`Icon imports out of date (run npm run icons:sync):\n  ${changed.join('\n  ')}`);
  process.exit(1);
}
console.log(`${used.size} icons; ${check ? 'up to date' : `${changed.length} file(s) written`}`);
