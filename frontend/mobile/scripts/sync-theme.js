#!/usr/bin/env node
// Derives the mobile colour tokens from the web app's globals.css, so the two palettes can't drift.
//   node scripts/sync-theme.js          rewrites src/global.css and src/theme/colors.ts
//   node scripts/sync-theme.js --check  exits 1 if either file is out of date (for CI / pre-commit)
// React Native Reusables reads colours as HSL triplets (`hsl(var(--primary))`), so every hex
// token is converted. The dark `border` and `input` are translucent white on the web; a triplet
// can't carry alpha, so they are flattened over the dark `card` colour.
const fs = require("node:fs");
const path = require("node:path");

const WEB_CSS = path.resolve(__dirname, "../../web/app/globals.css");
const OUT_CSS = path.resolve(__dirname, "../src/global.css");
const OUT_COLORS = path.resolve(__dirname, "../src/theme/colors.ts");

// The web tokens mobile uses (sidebar-*, elevation-* and the radius are web-only or fixed below).
const TOKENS = [
  "background", "foreground", "card", "card-foreground", "popover", "popover-foreground",
  "primary", "primary-text", "primary-foreground", "secondary", "secondary-foreground",
  "muted", "muted-foreground", "accent", "accent-foreground", "destructive", "destructive-foreground",
  "success", "warning", "border", "input", "ring",
  "chart-1", "chart-2", "chart-3", "chart-4", "chart-5", "chart-6", "bar",
];

/** The text of the first `selector { ... }` block that starts a line, or throws. */
function block(css, selector) {
  const start = css.search(new RegExp(`^${selector.replace(/[.:]/g, "\\$&")} \\{`, "m"));
  if (start < 0) throw new Error(`No "${selector}" block in the web globals.css`);
  const end = css.indexOf("\n}", start);
  return css.slice(start, end);
}

/** `--name: value;` pairs of a block, as a map (multi-line values are skipped: they are shadows, not colours). */
function declarations(body) {
  const out = {};
  for (const m of body.matchAll(/^\s+--([\w-]+):\s*([^;\n]+);/gm)) out[m[1]] = m[2].trim();
  return out;
}

const hexToRgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const rgbToHex = (rgb) => "#" + rgb.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");

/** `#rrggbb` or `rgba(r, g, b, a)` as an opaque rgb array, flattening any alpha over `backdrop` (rgb array). */
function toRgb(value, backdrop) {
  if (/^#[0-9a-f]{6}$/i.test(value)) return hexToRgb(value);
  const m = value.match(/^rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)$/);
  if (!m) throw new Error(`Unsupported colour value: ${value}`);
  if (!backdrop) throw new Error(`Translucent colour with nothing to flatten it over: ${value}`);
  const alpha = Number(m[4]);
  return [1, 2, 3].map((i) => alpha * Number(m[i]) + (1 - alpha) * backdrop[i - 1]);
}

/** rgb array to "H S% L%" with two decimals: the error back in rgb stays under half a unit. */
function toHslTriplet([r, g, b]) {
  const [R, G, B] = [r, g, b].map((v) => v / 255);
  const max = Math.max(R, G, B), min = Math.min(R, G, B), d = max - min;
  const l = (max + min) / 2;
  const s = d === 0 ? 0 : d / (1 - Math.abs(2 * l - 1));
  let h = 0;
  if (d !== 0) {
    if (max === R) h = ((G - B) / d) % 6;
    else if (max === G) h = (B - R) / d + 2;
    else h = (R - G) / d + 4;
    h = (h * 60 + 360) % 360;
  }
  const f = (n) => Number(n.toFixed(2));
  return `${f(h)} ${f(s * 100)}% ${f(l * 100)}%`;
}

/** Inverse of toHslTriplet, used by the test to prove the round trip stays within one rgb unit. */
function hslTripletToRgb(triplet) {
  const [h, s, l] = triplet.split(" ").map((v) => parseFloat(v));
  const S = s / 100, L = l / 100;
  const c = (1 - Math.abs(2 * L - 1)) * S, x = c * (1 - Math.abs(((h / 60) % 2) - 1)), m = L - c / 2;
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
  return [r + m, g + m, b + m].map((v) => Math.round(v * 255));
}

/** Parses the web file into { light, dark } maps of token to opaque rgb array, plus the radius. */
function parseWebTokens(css) {
  const light = declarations(block(css, ":root"));
  const dark = declarations(block(css, ".dark"));
  const darkBackdrop = hexToRgb(dark.card);
  const pick = (decls, backdrop) =>
    Object.fromEntries(TOKENS.map((t) => {
      if (!(t in decls)) throw new Error(`The web file has no --${t}`);
      return [t, toRgb(decls[t], backdrop)];
    }));
  return { light: pick(light), dark: pick(dark, darkBackdrop), radius: light.radius };
}

function renderCss({ light, dark, radius }) {
  const vars = (tokens) => TOKENS.map((t) => `    --${t}: ${toHslTriplet(tokens[t])};`).join("\n");
  return `/* GENERATED by scripts/sync-theme.js from the web app's globals.css. Do not edit by hand:
   change the web tokens, then run \`npm run theme:sync\`. */
@tailwind base;
@tailwind components;
@tailwind utilities;

@layer base {
  :root {
    --radius: ${radius};
${vars(light)}
  }

  .dark:root {
${vars(dark)}
  }
}

@layer base {
  /* react-native-web gives Text and TextInput their own font; on web inherit the page font instead.
     :where() keeps this rule's specificity at zero so a font-* utility on the element still wins. */
  :where(html) [class*='css-text-'],
  :where(html) [class*='css-textinput-'] {
    font-family: inherit;
  }
}
`;
}

function renderColors({ light, dark }) {
  const obj = (tokens) => TOKENS.map((t) => `    "${t}": "${rgbToHex(tokens[t])}",`).join("\n");
  return `// GENERATED by scripts/sync-theme.js from the web app's globals.css. Do not edit by hand.
// Hex values for what can't read CSS variables (navigation theme, status bar, SVG fills).
export const COLORS = {
  light: {
${obj(light)}
  },
  dark: {
${obj(dark)}
  },
} as const;

export type ColorToken = keyof typeof COLORS.light;
`;
}

function build() {
  const tokens = parseWebTokens(fs.readFileSync(WEB_CSS, "utf8"));
  return { css: renderCss(tokens), colors: renderColors(tokens) };
}

function main() {
  const { css, colors } = build();
  if (process.argv.includes("--check")) {
    const stale = [[OUT_CSS, css], [OUT_COLORS, colors]].filter(([file, want]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== want);
    if (stale.length) {
      console.error("Out of date with the web tokens:\n" + stale.map(([f]) => "  " + path.relative(process.cwd(), f)).join("\n") + "\nRun: npm run theme:sync");
      process.exit(1);
    }
    console.log("Theme tokens match the web app.");
    return;
  }
  fs.writeFileSync(OUT_CSS, css);
  fs.writeFileSync(OUT_COLORS, colors);
  console.log(`Wrote ${path.relative(process.cwd(), OUT_CSS)} and ${path.relative(process.cwd(), OUT_COLORS)}`);
}

module.exports = { TOKENS, block, declarations, toRgb, toHslTriplet, hslTripletToRgb, parseWebTokens, renderCss, renderColors, build };
if (require.main === module) main();
